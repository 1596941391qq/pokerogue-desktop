#!/usr/bin/env node
// 把 coop/mods/*/ 里的 mod 打包成 coop/mods-local.js（注入到游戏页面）。
//
// 每个 mod 一个目录：
//   mod.json   清单（id、名字、版本、作者、说明、api、modes、default）
//   mod.js     主体（CoopMods.define('<id>', function (api) { ... })）
//   icons/     可选：32x32 的 PNG，文件名去掉 .png 就是图标名
//
// 生成的每一段和上游的 coop/mods-bundle.js 一个格式：
//   if (CoopMods.manifest({...})) { if (CoopMods.icons) CoopMods.icons("<id>", {...}); <mod.js> }
//
// 上游那份 coop/mods-bundle.js 是 scripts/sync-coop.sh 从合作项目同步过来的，这个脚本不动它；
// 两份一起注入（main.mjs 的 modsJs()），所以本地 mod 和上游 mod 可以同时存在。
//
//   node tools/build-mods.mjs                       # coop/mods/* -> coop/mods-local.js
//   node tools/build-mods.mjs --src <dir> --out <f>  # 换个源目录 / 输出文件
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync, statSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const argv = process.argv.slice(2)
const arg = (name, dflt) => { const i = argv.indexOf(name); return i >= 0 && argv[i + 1] ? argv[i + 1] : dflt }
const SRC = path.resolve(arg('--src', path.join(ROOT, 'coop', 'mods')))
const OUT = path.resolve(arg('--out', path.join(ROOT, 'coop', 'mods-local.js')))
const API_MAX = 3 // 这套引擎的接口版本（coop/host-mods.js 里的 API_VERSION）

const fail = msg => { console.error('build-mods: ' + msg); process.exit(1) }

// ---- 读一个 mod 目录 ----
function readMod(dir, name) {
  const base = path.join(dir, name)
  const manifestPath = path.join(base, 'mod.json')
  if (!existsSync(manifestPath)) fail(name + ': mod.json 不存在')
  let manifest
  try { manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) } catch (e) { fail(name + ': mod.json 读不出来（' + e.message + '）') }
  if (!manifest || typeof manifest !== 'object') fail(name + ': mod.json 不是对象')
  if (typeof manifest.id !== 'string' || !/^[a-z0-9][a-z0-9-]{2,39}$/.test(manifest.id)) fail(name + ': id 不合法（' + manifest.id + '），只能用小写字母、数字和 -')
  if (manifest.id !== name) fail(name + ': 目录名和 mod.json 里的 id（' + manifest.id + '）不一样')
  if (!manifest.name) fail(name + ': mod.json 少了 name')
  if (!manifest.version) fail(name + ': mod.json 少了 version')
  if (Number(manifest.api || 1) > API_MAX) fail(name + ': 需要接口版本 ' + manifest.api + '，这套引擎只有 ' + API_MAX)

  const jsPath = path.join(base, 'mod.js')
  if (!existsSync(jsPath)) fail(name + ': mod.js 不存在')
  const body = readFileSync(jsPath, 'utf8')
  if (!body.includes("CoopMods.define('" + manifest.id + "'") && !body.includes('CoopMods.define("' + manifest.id + '"')) {
    fail(name + ": mod.js 里没有 CoopMods.define('" + manifest.id + "', ...)")
  }

  // 图标：32x32 的 PNG，打包成 data URI
  const icons = {}
  const iconDir = path.join(base, 'icons')
  if (existsSync(iconDir) && statSync(iconDir).isDirectory()) {
    for (const f of readdirSync(iconDir).sort()) {
      if (!f.toLowerCase().endsWith('.png')) continue
      const key = f.replace(/\.png$/i, '')
      if (!/^[a-z0-9][a-z0-9-]{0,39}$/.test(key)) fail(name + ': 图标名不合法（' + f + '）')
      icons[key] = 'data:image/png;base64,' + readFileSync(path.join(iconDir, f)).toString('base64')
    }
  }
  return { manifest, body, icons }
}

// ---- 打包 ----
if (!existsSync(SRC)) fail('源目录不存在：' + SRC)
const names = readdirSync(SRC).filter(n => !n.startsWith('.') && statSync(path.join(SRC, n)).isDirectory()).sort()
if (!names.length) fail('源目录里没有 mod：' + SRC)

const parts = [
  '// Generated by tools/build-mods.mjs from ' + path.relative(ROOT, SRC) + '/*/ (mod.json + mod.js + icons). Do not edit: change the mod and rebuild.',
  '',
]
for (const name of names) {
  const mod = readMod(SRC, name)
  const m = mod.manifest
  parts.push('// ---- ' + m.id + ' ' + m.version + ' ----')
  parts.push('if (CoopMods.manifest(' + JSON.stringify(m) + ')) {')
  const iconKeys = Object.keys(mod.icons)
  if (iconKeys.length) {
    parts.push('if (CoopMods.icons) CoopMods.icons(' + JSON.stringify(m.id) + ', {')
    iconKeys.forEach((k, i) => parts.push(' ' + JSON.stringify(k) + ': ' + JSON.stringify(mod.icons[k]) + (i < iconKeys.length - 1 ? ',' : '')))
    parts.push('});')
  }
  parts.push(mod.body.replace(/\s+$/, ''))
  parts.push('}')
  parts.push('')
}
parts.push('')
mkdirSync(path.dirname(OUT), { recursive: true })
writeFileSync(OUT, parts.join('\n'))
console.log('build-mods: ' + names.length + ' 个 mod -> ' + path.relative(ROOT, OUT) + '（' + names.join(', ') + '）')
